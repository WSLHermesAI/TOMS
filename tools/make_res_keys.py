"""make_res_keys.py -- writes src/core/game/core/res_keys.h from assets/media/resources.json (docs/engine/12_RESOURCE_MANAGER.md).

Code names files by key (toms::key::kDataItems = "data.items") and families by pattern (toms::pattern::kStage), never by
path, so a typo in a key does not compile and moving a file only changes resources.json.

  python tools/make_res_keys.py           write the header
  python tools/make_res_keys.py --check   exit 1 when the header is not what the manifest gives (unit.res_keys_test
                                          checks the same from C++)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'assets', 'media', 'resources.json')
HEADER = os.path.join(ROOT, 'src', 'core', 'game', 'core', 'res_keys.h')


def ident(name):
    """'data.weapon_play' -> 'kDataWeaponPlay'"""
    parts = [p for p in re.split(r'[^A-Za-z0-9]+', name) if p]
    return 'k' + ''.join(p[:1].upper() + p[1:] for p in parts)


def build():
    with open(MANIFEST, encoding='utf-8') as f:
        m = json.load(f)
    res, pats = m.get('resources', {}), m.get('patterns', {})
    out = ['// res_keys.h -- GENERATED by tools/make_res_keys.py from assets/media/resources.json. Do not edit: change the',
           '// manifest and run the script (unit.res_keys_test fails while this file is out of date).',
           '//',
           '//   res_->get<toms::res::AnimRes>(toms::key::kAnimDoorOpen);     a file, by key',
           '//   Game::pathOf(toms::key::kDataItems)                          its path (for loaders that read it themselves)',
           '//   Game::pathFor(toms::pattern::kStage, "stage01")              one of a family',
           '#pragma once', '', 'namespace toms {', '', 'namespace key {']
    names = sorted(res)
    seen = {}
    for k in names:
        i = ident(k)
        if i in seen: sys.exit('make_res_keys: keys "%s" and "%s" make the same name %s' % (seen[i], k, i))
        seen[i] = k
    w = max([len(ident(k)) for k in names] + [1])
    for k in names:
        out.append('inline constexpr const char %s = "%s";%s// %s %s' % (
            (ident(k) + '[]').ljust(w + 2), k, ' ' * max(1, 24 - len(k)), res[k].get('type', ''), res[k].get('path', '')))
    out.append('// every key, for the test that keeps this file and the manifest the same')
    out.append('inline constexpr const char* kAll[] = {')
    out += ['    %s,' % ident(k) for k in names]
    out += ['};', '}  // namespace key', '', 'namespace pattern {']
    pnames = sorted(pats)
    w = max([len(ident(p)) for p in pnames] + [1])
    for p in pnames:
        out.append('inline constexpr const char %s = "%s";%s// %s' % ((ident(p) + '[]').ljust(w + 2), p, ' ' * max(1, 16 - len(p)), pats[p]))
    out.append('inline constexpr const char* kAll[] = {')
    out += ['    %s,' % ident(p) for p in pnames]
    out += ['};', '}  // namespace pattern', '', '}  // namespace toms', '']
    return '\n'.join(out)


def main():
    text = build()
    if '--check' in sys.argv:
        try:
            with open(HEADER, encoding='utf-8') as f: same = f.read() == text
        except OSError:
            same = False
        if not same:
            print('res_keys.h is out of date: run python tools/make_res_keys.py')
            return 1
        print('res_keys.h is up to date')
        return 0
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as f: f.write(text)
    print('wrote', os.path.relpath(HEADER, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
