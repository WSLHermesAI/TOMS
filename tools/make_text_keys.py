"""make_text_keys.py -- writes src/core/game/core/text_keys.h from assets/data/text.json (docs/project/12_CPP_NAMING.md §7).

The sibling of make_res_keys.py (res_keys.h: a file by its key): code names a line of text by its key's constant,
toms::text::g_pszBattleWordParry = "battle.word_parry", never by the string, so a misspelt or removed key does not
compile.

  python tools/make_text_keys.py           write the header
  python tools/make_text_keys.py --check   exit 1 when the header is not what text.json gives (test data.text_keys_up_to_date)

Run it after adding, renaming or removing a key in text.json's "strings".
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_res_keys import ident   # the same names: 'battle.word_parry' -> g_pszBattleWordParry

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT = os.path.join(ROOT, 'assets', 'data', 'text.json')
HEADER = os.path.join(ROOT, 'src', 'core', 'game', 'core', 'text_keys.h')


def build():
    with open(TEXT, encoding='utf-8') as f:
        keys = sorted(json.load(f).get('strings', {}))
    seen = {}
    for k in keys:
        i = ident(k)
        if i in seen:
            sys.exit('make_text_keys: keys "%s" and "%s" make the same name %s' % (seen[i], k, i))
        seen[i] = k
    out = ['// text_keys.h -- GENERATED by tools/make_text_keys.py from assets/data/text.json ("strings"). Do not edit: change',
           '// text.json and run the script (data.text_keys_up_to_date fails while this file is out of date).',
           '//',
           '//   m_oLocale.f_Tr(toms::text::g_pszBattleWordParry)   a line of text, by its key',
           '#pragma once', '', 'namespace toms {', 'namespace text {', '']
    w = max([len(ident(k)) for k in keys] + [1])
    out += ['inline constexpr const char %s = "%s";' % ((ident(k) + '[]').ljust(w + 2), k) for k in keys]
    out += ['', '}  // namespace text', '}  // namespace toms', '']
    return '\n'.join(out)


def main():
    text = build()
    if '--check' in sys.argv:
        try:
            with open(HEADER, encoding='utf-8') as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            print('text_keys.h is out of date: run python tools/make_text_keys.py')
            return 1
        print('text_keys.h is up to date')
        return 0
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.relpath(HEADER, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
