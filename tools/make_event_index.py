#!/usr/bin/env python3
"""make_event_index.py -- the per-floor event index (the owner's Q10 answer, 2026-10-12).

What can happen on a floor is spread over several files: the floor spec's `events` list, the events its grid
places (legend "event:<id>"), the chapter's story beats on that floor, and stairs locked behind an event. This
script reads them all and writes one file for quick search:

    assets/data/events/floor_index.json
    {
      "floors": {
        "F01": {
          "act": "ch_01", "map": "story/floors/F01.stage.json",
          "events": [ { "id": "ev_village_well", "kind": "whisper", "title": "The Reflection in the Well",
                        "pool": "pool_act01", "listed": true, "tiles": [[14, 5]] }, ... ],
          "beats":  [ { "id": "b_village_well", "kind": "event", "eventId": "ev_village_well" } ],
          "stairs": [ { "dir": "up", "to": "F02", "unlock": "ev_..." } ]       (only floors with a `stairs` list)
        }, ...
      },
      "events": { "ev_village_well": ["F01"], ... }                            (event -> the floors it is on)
    }

An event "listed" is in the spec's `events`; "tiles" is where the grid places it (empty: listed, not placed).
Titles are the English text (text.json), so a search by name works.

Usage:
    python tools/make_event_index.py           # write the index
    python tools/make_event_index.py --check   # exit 1 if the index is out of date (unit.event_index checks too)
Run it after editing floors, pools or chapters (tools/gen_floors.py runs it after it writes).
"""
import argparse
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'assets', 'data')
OUT = os.path.join(DATA, 'events', 'floor_index.json')


def load(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def build():
    strings = load(os.path.join(DATA, 'text.json')).get('strings', {})

    def english(key):
        v = strings.get(key)
        return v.get('en', '') if isinstance(v, dict) else ''

    pools = {}
    for p in sorted(glob.glob(os.path.join(DATA, 'events', 'pool_*.json'))):
        name = os.path.splitext(os.path.basename(p))[0]
        for e in load(p).get('events', []):
            pools[e['eventId']] = (name, e)

    beats = {}   # floor -> beats
    for p in sorted(glob.glob(os.path.join(DATA, 'story', 'chapters', '*.json'))):
        for b in load(p).get('beats', []):
            if b.get('floor'):
                beats.setdefault(b['floor'], []).append({k: b[k] for k in ('id', 'kind', 'eventId', 'nodeId', 'enemyId', 'shardId') if k in b})

    floors = {}
    for p in sorted(glob.glob(os.path.join(DATA, 'story', 'floors', 'F*.json'))):
        if p.endswith('.stage.json'):
            continue
        spec = load(p)
        fid = spec['id']
        if spec.get('handAuthoredStage'):
            map_rel = 'stages/' + spec['handAuthoredStage']
        else:
            map_rel = 'story/floors/%s.stage.json' % fid
        tiles = {}
        map_path = os.path.join(DATA, map_rel)
        if os.path.exists(map_path):
            grid = load(map_path)
            legend = grid.get('legend', {})
            for y, row in enumerate(grid.get('tiles', [])):
                for x, ch in enumerate(row):
                    kind = legend.get(ch, '')
                    if kind.startswith('event:'):
                        tiles.setdefault(kind[6:], []).append([x, y])
        listed = [e for e in spec.get('events', []) if isinstance(e, str)]
        ids = list(dict.fromkeys(listed + sorted(tiles)))
        events = []
        for eid in ids:
            pool, rec = pools.get(eid, (None, {}))
            events.append({
                'id': eid,
                'kind': rec.get('kind'),
                'title': english(rec.get('title', eid + '.title')) or None,
                'pool': pool,
                'listed': eid in listed,
                'tiles': tiles.get(eid, []),
            })
        entry = {'act': spec.get('act'), 'map': map_rel, 'events': events, 'beats': beats.get(fid, [])}
        if isinstance(spec.get('stairs'), list):
            entry['stairs'] = [{k: v for k, v in (('dir', s.get('dir', 'up')), ('to', s.get('to')),
                                                   ('unlock', (s.get('unlock') or {}).get('eventDone'))) if v}
                               for s in spec['stairs']]
        floors[fid] = entry

    by_event = {}
    for fid, f in floors.items():
        for e in f['events']:
            by_event.setdefault(e['id'], []).append(fid)
        for b in f['beats']:
            if b.get('eventId') and fid not in by_event.setdefault(b['eventId'], []):
                by_event[b['eventId']].append(fid)
        for s in f.get('stairs', []):
            if s.get('unlock') and fid not in by_event.setdefault(s['unlock'], []):
                by_event[s['unlock']].append(fid)
    return {
        '_comment': 'Generated by tools/make_event_index.py -- do not edit. The events each floor lists or places, '
                    'its chapter beats and its stair locks; "events" maps an event to its floors (Q10).',
        'floors': floors,
        'events': dict(sorted(by_event.items())),
    }


def text_of(index):
    return json.dumps(index, ensure_ascii=False, indent=1) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='exit 1 if the index is out of date')
    args = ap.parse_args()
    want = text_of(build())
    have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if args.check:
        if have != want:
            print('make_event_index: %s is out of date; run python tools/make_event_index.py' % os.path.relpath(OUT, ROOT))
            return 1
        print('make_event_index: up to date')
        return 0
    if have != want:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(want)
    index = json.loads(want)
    print('make_event_index: %d floors, %d events -> %s' % (len(index['floors']), len(index['events']), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
