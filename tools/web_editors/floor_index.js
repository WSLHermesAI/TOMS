// floor_index.js -- the per-floor event index, assets/data/events/floor_index.json (the owner's Q10 answer).
//
// Both HTML editors call syncFloorIndex(dir) when they open the project folder and after every Save into it: it
// reads the floors, their maps, the event pools, the chapters and text.json from the folder, builds the index and
// writes it only when it changed. So the index always matches the files on disk, whichever editor saved them, and a
// hand edit is picked up the next time an editor opens the folder. unit.floor_index_test checks it.
//
//   { "floors": { "F01": { "act", "map", "events": [ { "id", "kind", "title", "pool", "listed", "tiles" } ],
//                          "beats": [...], "stairs": [...] (only floors with a `stairs` list) } },
//     "events": { "<event id>": ["F01", ...] } }
//
// "listed": the event is in the spec's `events`; "tiles": where the grid places it. Titles are the English text.
'use strict';
(function () {
  const A = 'assets/data/';
  async function dirIn(dir, path) {
    let h = dir;
    for (const p of path.split('/').filter(Boolean)) h = await h.getDirectoryHandle(p);
    return h;
  }
  async function fileIn(dir, path, create) {
    const parts = path.split('/');
    let h = dir;
    for (const p of parts.slice(0, -1)) h = await h.getDirectoryHandle(p, { create: !!create });
    return h.getFileHandle(parts.at(-1), { create: !!create });
  }
  async function readText(dir, path) {
    try { return await (await (await fileIn(dir, path)).getFile()).text(); } catch (_) { return null; }
  }
  async function readJson(dir, path) { const s = await readText(dir, path); return s == null ? null : JSON.parse(s); }
  async function names(dir, path, re) {
    const out = [];
    try { for await (const [n, h] of (await dirIn(dir, path)).entries()) if (h.kind === 'file' && re.test(n)) out.push(n); }
    catch (_) {}
    return out.sort();
  }
  const pick = (o, keys) => Object.fromEntries(keys.filter(k => k in o).map(k => [k, o[k]]));

  async function buildFloorIndex(dir) {
    const strings = ((await readJson(dir, A + 'text.json')) || {}).strings || {};
    const english = key => { const v = strings[key]; return v && typeof v === 'object' ? (v.en || '') : ''; };
    const pools = {};
    for (const n of await names(dir, A + 'events', /^pool_.*\.json$/)) {
      const p = await readJson(dir, A + 'events/' + n);
      for (const e of (p && p.events) || []) pools[e.eventId] = [n.slice(0, -5), e];
    }
    const beats = {};
    for (const n of await names(dir, A + 'story/chapters', /\.json$/)) {
      const ch = await readJson(dir, A + 'story/chapters/' + n);
      for (const b of (ch && ch.beats) || [])
        if (b.floor) (beats[b.floor] = beats[b.floor] || []).push(pick(b, ['id', 'kind', 'eventId', 'nodeId', 'enemyId', 'shardId']));
    }
    const floors = {};
    for (const n of await names(dir, A + 'story/floors', /^F.*\.json$/)) {
      if (n.endsWith('.stage.json')) continue;
      const spec = await readJson(dir, A + 'story/floors/' + n);
      const fid = spec.id;
      const map = spec.handAuthoredStage ? 'stages/' + spec.handAuthoredStage : `story/floors/${fid}.stage.json`;
      const tiles = {};
      const grid = await readJson(dir, A + map);
      if (grid) {
        const legend = grid.legend || {};
        (grid.tiles || []).forEach((row, y) => [...row].forEach((ch, x) => {
          const kind = legend[ch] || '';
          if (kind.startsWith('event:')) (tiles[kind.slice(6)] = tiles[kind.slice(6)] || []).push([x, y]);
        }));
      }
      const listed = (spec.events || []).filter(e => typeof e === 'string');
      const ids = [...new Set([...listed, ...Object.keys(tiles).sort()])];
      const events = ids.map(id => {
        const [pool, rec] = pools[id] || [null, {}];
        return { id, kind: rec.kind ?? null, title: english(rec.title || id + '.title') || null, pool,
                 listed: listed.includes(id), tiles: tiles[id] || [] };
      });
      const entry = { act: spec.act ?? null, map, events, beats: beats[fid] || [] };
      if (Array.isArray(spec.stairs))
        entry.stairs = spec.stairs.map(s => Object.fromEntries(
          [['dir', s.dir || 'up'], ['to', s.to], ['unlock', (s.unlock || {}).eventDone]].filter(([, v]) => v)));
      floors[fid] = entry;
    }
    const byEvent = {};
    const add = (id, fid) => { const l = byEvent[id] = byEvent[id] || []; if (!l.includes(fid)) l.push(fid); };
    for (const [fid, f] of Object.entries(floors)) {
      for (const e of f.events) (byEvent[e.id] = byEvent[e.id] || []).push(fid);
      for (const b of f.beats) if (b.eventId) add(b.eventId, fid);
      for (const s of f.stairs || []) if (s.unlock) add(s.unlock, fid);
    }
    const sorted = Object.fromEntries(Object.keys(byEvent).sort().map(k => [k, byEvent[k]]));
    return {
      _comment: 'Generated by the HTML editors (tools/web_editors/floor_index.js) -- do not edit. The events each floor lists ' +
                'or places, its chapter beats and its stair locks; "events" maps an event to its floors (Q10).',
      floors, events: sorted,
    };
  }

  // Rebuilds the index from the folder; writes it only when it changed. Returns true when it wrote.
  async function syncFloorIndex(dir) {
    const text = JSON.stringify(await buildFloorIndex(dir), null, 1) + '\n';
    const path = A + 'events/floor_index.json';
    if ((await readText(dir, path)) === text) return false;
    const w = await (await fileIn(dir, path, true)).createWritable();
    await w.write(text);
    await w.close();
    return true;
  }

  window.buildFloorIndex = buildFloorIndex;
  window.syncFloorIndex = syncFloorIndex;
})();
